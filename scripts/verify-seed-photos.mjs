#!/usr/bin/env node
/**
 * Verifies the Wikimedia Commons photos referenced in supabase/seed.sql.
 *
 * For every Special:FilePath URL it queries the Commons API and reports:
 *   - files that do not exist (fix or remove them in seed.sql)
 *   - author + licence for files that exist, emitted as SQL UPDATE statements
 *     you can run against your database (or paste into a new migration).
 *
 * Usage: node scripts/verify-seed-photos.mjs [--sql out.sql]
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const seed = fs.readFileSync(path.join(root, "supabase/seed.sql"), "utf8");
const outIdx = process.argv.indexOf("--sql");
const outFile = outIdx > -1 ? process.argv[outIdx + 1] : null;

// Rows look like: ('slug', 'File name.jpg', 'Caption'),
const files = [...seed.matchAll(/\(\s*'([a-z0-9-]+)',\s*'([^']+\.(?:jpe?g|png|webp|gif|tiff?))',\s*'[^']*'\)/gi)].map((m) => ({
  slug: m[1],
  file: m[2],
}));

if (!files.length) {
  console.error("No Commons files found in seed.sql");
  process.exit(1);
}

const strip = (html = "") => html.replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();
const sqlString = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);

async function lookup(batch) {
  const titles = batch.map((f) => `File:${f.file}`).join("|");
  const url = new URL("https://commons.wikimedia.org/w/api.php");
  url.search = new URLSearchParams({
    action: "query",
    format: "json",
    formatversion: "2",
    titles,
    prop: "imageinfo",
    iiprop: "url|extmetadata",
    iiextmetadatafilter: "Artist|LicenseShortName|LicenseUrl",
  }).toString();
  const res = await fetch(url, { headers: { "User-Agent": "OpenDiveAtlas-seed-verifier/1.0 (https://github.com/nohearseeno/opendive-atlas)" } });
  if (!res.ok) throw new Error(`Commons API ${res.status}`);
  return (await res.json()).query;
}

const missing = [];
const updates = [];
for (let i = 0; i < files.length; i += 40) {
  const batch = files.slice(i, i + 40);
  const query = await lookup(batch);
  const normalized = new Map((query.normalized ?? []).map((n) => [n.to, n.from]));
  for (const page of query.pages) {
    const from = normalized.get(page.title) ?? page.title;
    const entry = batch.find((f) => `File:${f.file}` === from || `File:${f.file.replace(/_/g, " ")}` === page.title);
    if (!entry) continue;
    if (page.missing || !page.imageinfo?.length) {
      missing.push(entry);
      continue;
    }
    const meta = page.imageinfo[0].extmetadata ?? {};
    const artist = strip(meta.Artist?.value) || "Unknown author";
    const license = strip(meta.LicenseShortName?.value) || "See source";
    const fileUrl = `https://commons.wikimedia.org/wiki/Special:FilePath/${entry.file.replace(/ /g, "_")}?width=1280`;
    updates.push(
      `update public.photos set attribution = ${sqlString(`${artist} / Wikimedia Commons`)}, license = ${sqlString(license)} where external_url = ${sqlString(fileUrl)};`,
    );
    console.log(`OK       ${entry.slug.padEnd(26)} ${entry.file}  —  ${artist} (${license})`);
  }
}

for (const m of missing) console.log(`MISSING  ${m.slug.padEnd(26)} ${m.file}`);
console.log(`\n${files.length - missing.length}/${files.length} files found.`);

if (outFile) {
  fs.writeFileSync(outFile, `-- Generated by scripts/verify-seed-photos.mjs on ${new Date().toISOString()}\n${updates.join("\n")}\n`);
  console.log(`Wrote ${updates.length} UPDATE statements to ${outFile}`);
}
process.exit(missing.length ? 2 : 0);
